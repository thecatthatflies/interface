#!/usr/bin/env node
// Brand guidelines page from brand.json, the logo files, palette tokens and exported assets.
//
//   node book.mjs <brand.json> [--out <dir>]
//
// Writes <out>/index.html (self-contained apart from web fonts and the asset images it copies) and
// <out>/type.css (the type scale as custom properties). The page is the brand's single source a person
// or an agent can read: idea, personality, logo use and misuse, clear space, color roles with contrast,
// type specimens, voice, assets and tokens.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { arg, esc } from './lib.mjs'

const args = process.argv.slice(2)
if (!args[0]) {
  console.log('usage: node book.mjs <brand.json> [--out <dir>]')
  process.exit(1)
}
const brandPath = resolve(args[0])
const base = dirname(brandPath)
const B = JSON.parse(readFileSync(brandPath, 'utf8'))
const out = resolve(arg(args, '--out', join(base, 'brand-book')))
mkdirSync(out, { recursive: true })
const read = (p) => (p && existsSync(resolve(base, p)) ? readFileSync(resolve(base, p), 'utf8').replace(/<\?xml[^>]*>/, '').trim() : null)
const tokens = JSON.parse(read(B.tokens ?? 'tokens/tokens.json') ?? '{}')
const contrast = JSON.parse(read((B.tokens ? dirname(B.tokens) : 'tokens') + '/contrast.json') ?? '{"checks":[]}')
const role = (m, r, f) => tokens[m]?.[r]?.$value ?? f
const L = (r, f) => role('light', r, f), D = (r, f) => role('dark', r, f)
const mark = read(B.logo?.mark), lockup = read(B.logo?.primary) ?? mark
const svgFit = (svg, extra = '') => (svg ?? '').replace('<svg', `<svg width="100%" height="100%" preserveAspectRatio="xMidYMid meet" ${extra}`)

// ---------- type scale ----------
const T = B.type ?? {}
const baseSize = T.scale?.base ?? 16, ratio = T.scale?.ratio ?? 1.25
const steps = { xs: -2, sm: -1, base: 0, lg: 1, xl: 2, '2xl': 3, '3xl': 4, '4xl': 5, '5xl': 6 }
// Steps below base never go under 12px: smaller text fails readers long before it fails a checker.
const size = (n) => +Math.max(n < 0 ? 12 : 0, baseSize * ratio ** n).toFixed(2)
const fam = (f, fallback) => (f?.family ? `'${f.family}', ${f.fallback ?? fallback}` : fallback)
const families = { display: fam(T.display, 'Georgia, serif'), text: fam(T.text, 'system-ui, sans-serif'), mono: fam(T.mono, 'ui-monospace, monospace') }
const typeCss = `/* Generated by brand-identity/scripts/book.mjs from brand.json. */
:root {
  --font-display: ${families.display};
  --font-text: ${families.text};
  --font-mono: ${families.mono};
${Object.entries(steps).map(([k, n]) => `  --text-${k}: ${(size(n) / 16).toFixed(4).replace(/0+$/, '')}rem;`).join('\n')}
  --leading-tight: 1.1;
  --leading-snug: 1.3;
  --leading-body: 1.55;
  --measure: 66ch;
}
`
writeFileSync(join(out, 'type.css'), typeCss)
const gf = [T.display, T.text, T.mono].filter((f) => f?.family && (f.source ?? 'google') === 'google')
const fontHref = gf.length ? `https://fonts.googleapis.com/css2?${gf.map((f) => `family=${f.family.replace(/ /g, '+')}:wght@${(f.weights ?? [400, 600, 700]).join(';')}`).join('&')}&display=swap` : null

// ---------- assets ----------
const assetDir = resolve(base, B.assets ?? 'assets')
const assetFiles = ['og-image.png', 'icon-512.png', 'icon-maskable-512.png', 'apple-touch-icon.png', 'favicon.svg']
const shown = []
for (const f of assetFiles) if (existsSync(join(assetDir, f))) { copyFileSync(join(assetDir, f), join(out, f)); shown.push(f) }
if (existsSync(join(assetDir, 'favicon.ico'))) copyFileSync(join(assetDir, 'favicon.ico'), join(out, 'favicon.ico'))

// ---------- sections ----------
const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const labelOn = (hex) => ((lum(hex) + 0.05) / 0.05 >= 1.05 / (lum(hex) + 0.05) ? '#000' : '#fff')
const ramps = Object.entries(tokens.color ?? {})
const rampHtml = ramps
  .map(([name, st]) => `<div class="ramp"><h3 class="rh">${esc(name)}</h3><ol style="--n:${Object.keys(st).length}">${Object.entries(st).map(([s, v]) => `<li style="background:${v.$value};color:${labelOn(v.$value)}"><span>${s}</span><code>${v.$value}</code></li>`).join('')}</ol></div>`)
  .join('')
const roleList = ['bg', 'surface', 'text', 'text-muted', 'border', 'primary', 'on-primary', 'primary-text', 'focus', 'success-text', 'warning-text', 'danger-text', 'info-text']
const roleRows = roleList.filter((r) => tokens.light?.[r]).map((r) => `<tr><th scope="row"><code>--color-${r}</code></th><td><i style="background:${L(r)}"></i>${L(r)}</td><td><i style="background:${D(r)}"></i>${D(r)}</td></tr>`).join('')
const fails = contrast.checks.filter((c) => !c.pass && !c.advisory)
const minRatio = contrast.checks.length ? Math.min(...contrast.checks.filter((c) => !c.advisory).map((c) => c.ratio)) : null

const misuse = [
  ['Stretched', 'transform:scaleX(1.45)'],
  ['Rotated', 'transform:rotate(-12deg)'],
  ['Recolored', `color:#7a3cff`],
  ['Effects added', 'filter:drop-shadow(4px 6px 0 #0006) blur(.4px)'],
  ['On a busy image', `color:#fff;background:repeating-linear-gradient(35deg,#8a6d4f 0 6px,#d8cbb6 6px 14px)`],
  ['Low contrast', `color:${L('border', '#ddd')}`],
]
const voice = B.voice ?? {}
const chips = (list) => (list ?? []).map((x) => `<li>${esc(x)}</li>`).join('')

const html = `<!doctype html>
<html lang="${esc(B.lang ?? 'en')}">
<head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(B.name)} brand guidelines</title>
<meta name="description" content="${esc(B.tagline ?? '')}">
${shown.includes('favicon.svg') ? '<link rel="icon" href="favicon.svg" type="image/svg+xml">' : ''}
${fontHref ? `<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link rel="stylesheet" href="${fontHref}">` : ''}
<link rel="stylesheet" href="type.css">
<style>
:root{--bg:${L('bg', '#fbfaf8')};--surface:${L('surface', '#fff')};--text:${L('text', '#16181d')};--muted:${L('text-muted', '#5b6070')};--border:${L('border', '#e3e1dc')};--primary:${L('primary', '#1f4fd1')};--on-primary:${L('on-primary', '#fff')};--ptext:${L('primary-text', '#1f4fd1')};--focus:${L('focus', '#1f4fd1')};color-scheme:light}
@media (prefers-color-scheme:dark){:root{--bg:${D('bg', '#111317')};--surface:${D('surface', '#181a1f')};--text:${D('text', '#f2f2f0')};--muted:${D('text-muted', '#a3a7b3')};--border:${D('border', '#2b2e35')};--primary:${D('primary', '#7d9cff')};--on-primary:${D('on-primary', '#111')};--ptext:${D('primary-text', '#9db4ff')};--focus:${D('focus', '#9db4ff')};color-scheme:dark}}
*{box-sizing:border-box}html{scroll-behavior:smooth}@media (prefers-reduced-motion:reduce){html{scroll-behavior:auto}}
body{margin:0;background:var(--bg);color:var(--text);font:var(--text-base)/var(--leading-body) var(--font-text)}
a{color:var(--ptext)}:focus-visible{outline:3px solid var(--focus);outline-offset:2px}
.skip{position:absolute;left:-999px;padding:12px 16px}.skip:focus{left:16px;top:16px;background:var(--surface);padding:8px 12px;z-index:9}
header.top{position:sticky;top:0;z-index:5;background:color-mix(in oklab,var(--bg) 88%,transparent);backdrop-filter:blur(8px);border-bottom:1px solid var(--border)}
header.top .in{max-width:1180px;margin:auto;padding:12px 24px;display:flex;gap:24px;align-items:center}
header.top .brand{height:28px;display:block;width:120px;color:var(--text)}
nav ul{display:flex;gap:4px 18px;flex-wrap:wrap;list-style:none;margin:0;padding:0}nav a{color:var(--muted);text-decoration:none;font-size:var(--text-sm)}nav a:hover{color:var(--text)}
main{max-width:1180px;margin:auto;padding:0 24px 120px}
section{padding:96px 0 0;scroll-margin-top:60px}
h1,h2,h3{font-family:var(--font-display);line-height:var(--leading-tight);letter-spacing:-.015em;margin:0}
h2{font-size:var(--text-3xl);margin-bottom:12px}h3{font-size:var(--text-xl);margin:40px 0 12px}.rh{margin:24px 0 8px;font:600 var(--text-sm)/1.3 var(--font-text);letter-spacing:0;text-transform:capitalize}
.lede{font-size:var(--text-lg);color:var(--muted);max-width:var(--measure);margin:0 0 32px}
.cover{min-height:78vh;display:grid;align-content:center;gap:40px;padding-top:40px}
.cover .lock{height:min(22vw,180px);color:var(--text)}.cover p{font-family:var(--font-display);font-size:var(--text-3xl);line-height:var(--leading-snug);max-width:22ch;margin:0}
.cover dl{display:flex;flex-wrap:wrap;gap:12px 40px;margin:0;color:var(--muted);font-size:var(--text-sm)}.cover dt{font-weight:600;color:var(--text)}.cover dd{margin:0}
.grid{display:grid;gap:16px}.g2{grid-template-columns:repeat(2,minmax(0,1fr))}.g3{grid-template-columns:repeat(3,minmax(0,1fr))}
.tile{border:1px solid var(--border);border-radius:14px;padding:28px;background:var(--surface);min-height:220px;display:grid;place-items:center;position:relative}
.tile figcaption{position:absolute;left:16px;bottom:12px;font-size:max(12px,var(--text-sm));color:inherit}
.tile .art{width:72%;height:110px}.tile.sq .art{width:120px;height:120px}
.clear{position:relative;padding:var(--cs);outline:1px dashed var(--muted);outline-offset:0;background:repeating-linear-gradient(45deg,transparent 0 6px,color-mix(in oklab,var(--primary) 12%,transparent) 6px 7px)}
.clear .inner{background:var(--surface);width:260px;height:90px;color:var(--text)}
.dont .art{opacity:.95}.dont figcaption::before{content:"✕ ";color:${L('danger-text', '#b42318')}}
.ramp ol{display:grid;grid-template-columns:repeat(var(--n,11),minmax(0,1fr));list-style:none;margin:0 0 20px;padding:0;border-radius:10px;overflow:hidden}
.ramp li{height:76px;padding:6px;font-size:12px;display:flex;flex-direction:column;justify-content:flex-end}
.ramp code{font-size:11px}
table{border-collapse:collapse;width:100%;font-size:var(--text-sm)}th,td{text-align:left;padding:10px 12px;border-bottom:1px solid var(--border)}td i{display:inline-block;width:14px;height:14px;border-radius:4px;vertical-align:-2px;margin-right:8px;border:1px solid var(--border)}
.spec{border-top:1px solid var(--border);padding:28px 0;display:grid;grid-template-columns:200px 1fr;gap:24px;align-items:baseline}
.spec .meta{font-size:var(--text-sm);color:var(--muted)}.spec .meta strong{display:block;color:var(--text);font-size:var(--text-base)}
.scale{display:grid;gap:6px}.scale div{display:grid;grid-template-columns:70px 1fr;align-items:baseline;gap:16px;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}.scale small{color:var(--muted);font:12px var(--font-mono)}
.voice ul{margin:0;padding-left:20px}.say{border-left:3px solid var(--primary);padding:6px 0 6px 16px;margin:12px 0}
.assets img{width:100%;height:auto;border-radius:12px;border:1px solid var(--border);background:var(--surface)}
pre{background:var(--surface);border:1px solid var(--border);border-radius:10px;padding:16px;overflow:auto;font:var(--text-sm)/1.5 var(--font-mono)}
.note{font-size:var(--text-sm);color:var(--muted)}
@media (max-width:760px){.g2,.g3{grid-template-columns:1fr}.spec{grid-template-columns:1fr}.ramp ol{grid-template-columns:repeat(6,1fr)}nav{display:none}h2{font-size:var(--text-2xl)}}
</style>
</head>
<body>
<a class="skip" href="#main">Skip to content</a>
<header class="top"><div class="in"><span class="brand" role="img" aria-label="${esc(B.name)}">${svgFit(lockup)}</span>
<nav aria-label="Sections"><ul><li><a href="#idea">Idea</a></li><li><a href="#logo">Logo</a></li><li><a href="#color">Color</a></li><li><a href="#type">Type</a></li><li><a href="#voice">Voice</a></li>${shown.length ? '<li><a href="#assets">Assets</a></li>' : ''}<li><a href="#tokens">Tokens</a></li></ul></nav></div></header>
<main id="main">
<section class="cover" aria-labelledby="cover-h"><h1 id="cover-h" class="lock" aria-label="${esc(B.name)} brand guidelines">${svgFit(lockup, 'aria-hidden="true" style="max-width:100%"')}</h1>
<p>${esc(B.tagline ?? '')}</p>
<dl>${B.version ? `<div><dt>Version</dt><dd>${esc(B.version)}</dd></div>` : ''}${B.url ? `<div><dt>Web</dt><dd>${esc(B.url)}</dd></div>` : ''}${T.display?.family ? `<div><dt>Type</dt><dd>${esc(T.display.family)}${T.text?.family && T.text.family !== T.display.family ? ` and ${esc(T.text.family)}` : ''}</dd></div>` : ''}<div><dt>Primary</dt><dd>${L('primary', '')}</dd></div></dl></section>

<section id="idea" aria-labelledby="idea-h"><h2 id="idea-h">The idea</h2>
<p class="lede">${esc(B.idea ?? '')}</p>
${B.personality?.length ? `<div class="grid g3">${B.personality.map((p) => `<div class="tile" style="min-height:140px;place-items:start"><div><h3 style="margin:0 0 8px">${esc(p.trait ?? p)}</h3><p class="note" style="margin:0">${esc(p.means ?? '')}</p></div></div>`).join('')}</div>` : ''}
${B.logo?.story ? `<h3>Why the mark looks like this</h3><p style="max-width:var(--measure)">${esc(B.logo.story)}</p>` : ''}
</section>

<section id="logo" aria-labelledby="logo-h"><h2 id="logo-h">Logo</h2>
<p class="lede">Use the files as supplied. The lockup leads; the mark stands alone only where space is square or tiny.</p>
<div class="grid g3">
<figure class="tile" style="background:${L('bg')};color:${L('text')}"><div class="art">${svgFit(lockup, 'aria-hidden="true"')}</div><figcaption>Primary, on light</figcaption></figure>
<figure class="tile" style="background:${D('bg', '#111')};color:${D('text', '#fff')}"><div class="art">${svgFit(lockup, 'aria-hidden="true"')}</div><figcaption>Primary, on dark</figcaption></figure>
<figure class="tile" style="background:${L('primary')};color:${L('on-primary')}"><div class="art">${svgFit(lockup, 'aria-hidden="true"')}</div><figcaption>Reversed, on brand</figcaption></figure>
${mark ? `<figure class="tile sq" style="background:${L('surface')};color:${L('text')}"><div class="art">${svgFit(mark, 'aria-hidden="true"')}</div><figcaption>Mark</figcaption></figure>
<figure class="tile sq" style="background:${L('primary')};color:${L('on-primary')}"><div class="art">${svgFit(mark, 'aria-hidden="true"')}</div><figcaption>Mark, app icon</figcaption></figure>
<figure class="tile sq" style="background:${L('surface')};color:${L('text')}"><div style="display:flex;gap:18px;align-items:end">${[16, 24, 32, 48].map((s) => `<span style="width:${s}px;height:${s}px;display:block">${svgFit(mark, 'aria-hidden="true"')}</span>`).join('')}</div><figcaption>Minimum ${esc(B.logo?.minSizePx ?? 16)} px</figcaption></figure>` : ''}
</div>
<h3>Clear space</h3>
<p style="max-width:var(--measure)">Keep at least ${esc(B.logo?.clearSpace ?? 'the height of the mark’s smallest counter, about 25% of the logo height,')} free of other elements on every side.</p>
<div class="tile" style="min-height:0"><div class="clear" style="--cs:28px"><div class="inner">${svgFit(lockup, 'aria-hidden="true"')}</div></div></div>
<h3>Do not</h3>
<div class="grid g3 dont">${misuse.map(([label, style]) => `<figure class="tile" style="min-height:160px;color:${L('text')}"><div class="art" style="${style}">${svgFit(lockup, 'aria-hidden="true"')}</div><figcaption>${label}</figcaption></figure>`).join('')}</div>
</section>

<section id="color" aria-labelledby="color-h"><h2 id="color-h">Color</h2>
<p class="lede">${esc(B.colorStory ?? 'Every color is a role first and a value second. Build with the roles; the ramps exist for the rare case a role does not cover.')}</p>
${rampHtml}
<h3>Roles</h3>
<table><thead><tr><th>Role</th><th>Light</th><th>Dark</th></tr></thead><tbody>${roleRows}</tbody></table>
<p class="note">${contrast.checks.length ? (fails.length ? `${fails.length} required contrast pair(s) fail; fix before use.` : `All ${contrast.checks.filter((c) => !c.advisory).length} required pairs meet WCAG 2.2 AA; the lowest is ${minRatio}:1.`) : 'Run palette.mjs to verify contrast.'} Status colors are separate from brand colors so danger always reads as danger.</p>
</section>

<section id="type" aria-labelledby="type-h"><h2 id="type-h">Typography</h2>
<p class="lede">${esc(T.story ?? '')}</p>
${['display', 'text', 'mono'].filter((k) => T[k]?.family).map((k) => `<div class="spec"><div class="meta"><strong>${esc(T[k].family)}</strong>${k} · ${esc((T[k].weights ?? [400, 600, 700]).join(', '))}<br>${esc(T[k].license ?? (T[k].source ?? 'google') === 'google' ? 'SIL Open Font License, via Google Fonts' : '')}</div><div style="font-family:var(--font-${k});font-size:${k === 'display' ? 'var(--text-4xl)' : 'var(--text-xl)'};line-height:1.15">${esc(T[k].sample ?? (k === 'display' ? B.tagline ?? B.name : k === 'mono' ? 'const total = rows.reduce(sum, 0) // 3,113,768' : 'The quick brown fox jumps over the lazy dog. 0123456789'))}</div></div>`).join('')}
<h3>Scale</h3>
<p class="note">Base ${baseSize}px, ratio ${ratio}. Sizes are in rem so they follow the reader's browser setting.</p>
<div class="scale">${Object.entries(steps).reverse().map(([k, n]) => `<div><small>${k} ${size(n)}</small><span style="font-family:var(--font-${n >= 2 ? 'display' : 'text'});font-size:var(--text-${k});line-height:1.15">${esc(B.name)} ${n >= 2 ? '' : '— body and interface text'}</span></div>`).join('')}</div>
</section>

<section id="voice" aria-labelledby="voice-h" class="voice"><h2 id="voice-h">Voice</h2>
<div class="grid g2"><div class="tile" style="place-items:start"><div><h3 style="margin-top:0">We are</h3><ul>${chips(voice.is)}</ul></div></div><div class="tile" style="place-items:start"><div><h3 style="margin-top:0">We are not</h3><ul>${chips(voice.isnt)}</ul></div></div></div>
${(voice.examples ?? []).map((e) => `<div class="say"><p style="margin:0"><strong>Say</strong> ${esc(e.say)}</p>${e.not ? `<p class="note" style="margin:4px 0 0">Not: ${esc(e.not)}</p>` : ''}</div>`).join('')}
</section>

${shown.length ? `<section id="assets" aria-labelledby="assets-h"><h2 id="assets-h">Assets</h2><div class="grid g3 assets">${shown.filter((f) => f.endsWith('.png')).map((f) => `<figure style="margin:0"><img src="${f}" alt="${esc(B.name)} ${f.replace(/[-.]/g, ' ').replace(' png', '')}"><figcaption class="note">${f}</figcaption></figure>`).join('')}</div></section>` : ''}

<section id="tokens" aria-labelledby="tokens-h"><h2 id="tokens-h">Tokens</h2>
<p class="lede">Ship these, not hex codes copied by hand. Colors: <code>tokens.css</code>, <code>tokens.json</code> (W3C Design Tokens), <code>tailwind.preset.cjs</code>. Type: <code>type.css</code>.</p>
<pre tabindex="0"><code>${esc(`<link rel="stylesheet" href="tokens.css">\n<link rel="stylesheet" href="type.css">\n\nbutton.primary {\n  background: var(--color-primary);\n  color: var(--color-on-primary);\n  font: 600 var(--text-base)/1 var(--font-text);\n}`)}</code></pre>
</section>
</main>
</body></html>
`
writeFileSync(join(out, 'index.html'), html)
console.log(`Wrote ${out}/index.html and type.css. Open it, and run the interface-guidelines audit on it if installed.`)
